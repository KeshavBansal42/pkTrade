// Command pktables generates the cross-generation reference tables used by
// internal/xgen and internal/pokemon.
//
// It reads three inputs:
//   - the CSV exports of the PokeAPI dataset (downloaded into -data when absent),
//   - the existing internal/xgen/moves.go move-id maps,
//   - the existing internal/xgen/items.go item-id maps (left untouched).
//
// It writes internal/pokemon/data_gender.go, internal/pokemon/data_gen1types.go
// and internal/xgen/data_moves.go.
//
// Run from the repository root:
//
//	go run ./tools/pktables
package main

import (
	"encoding/csv"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

const (
	baseURL = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv"
	header  = "// Code generated by tools/pktables from the PokeAPI dataset and the\n" +
		"// repository's own move/item id maps. DO NOT EDIT.\n\n"
)

func main() {
	dataDir := flag.String("data", "tools/pktables/data", "directory holding the PokeAPI CSV exports")
	flag.Parse()

	must(os.MkdirAll(*dataDir, 0o755))
	species := readCSV(*dataDir, "pokemon_species.csv")
	types := readCSV(*dataDir, "pokemon_types.csv")
	pokemon := readCSV(*dataDir, "pokemon.csv")
	moves := readCSV(*dataDir, "moves.csv")

	writeGender(species)
	writeGen1Types(species, types, pokemon)
	writeMoves(moves)
	fmt.Println("generated tables")
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "pktables:", err)
		os.Exit(1)
	}
}

// readCSV loads a CSV from dataDir, downloading it from PokeAPI when missing.
func readCSV(dir, name string) [][]string {
	path := filepath.Join(dir, name)
	if _, err := os.Stat(path); err != nil {
		resp, err := http.Get(baseURL + "/" + name)
		must(err)
		defer resp.Body.Close()
		if resp.StatusCode != 200 {
			must(fmt.Errorf("download %s: status %d", name, resp.StatusCode))
		}
		out, err := os.Create(path)
		must(err)
		_, err = io.Copy(out, resp.Body)
		out.Close()
		must(err)
	}
	f, err := os.Open(path)
	must(err)
	defer f.Close()
	rows, err := csv.NewReader(f).ReadAll()
	must(err)
	return rows
}

func headerIndex(row []string) map[string]int {
	idx := map[string]int{}
	for i, name := range row {
		idx[name] = i
	}
	return idx
}

func atoi(s string) int { v, _ := strconv.Atoi(strings.TrimSpace(s)); return v }

// ---- gender ratios -------------------------------------------------------

func writeGender(rows [][]string) {
	if len(rows) < 2 {
		must(fmt.Errorf("pokemon_species.csv is empty"))
	}
	idx := headerIndex(rows[0])
	var table [899]byte
	table[0] = 0
	for _, row := range rows[1:] {
		id := atoi(row[idx["id"]])
		if id < 1 || id > 898 {
			continue
		}
		rate := atoi(row[idx["gender_rate"]])
		table[id] = genderByte(rate)
	}
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("package pokemon\n\n")
	b.WriteString(`// GenderRatio is the per-species gender threshold in the Gen 2-5 numbering:
// 0 = male only, 254 = female only, 255 = genderless, otherwise a Pokémon is
// female when its personality low byte is below this value.
var GenderRatio = [899]byte{`)
	for i := 0; i < 899; i++ {
		if i%16 == 0 {
			b.WriteString("\n\t")
		}
		fmt.Fprintf(&b, "%d,", table[i])
	}
	b.WriteString("\n}\n")
	writeFile("internal/pokemon/data_gender.go", b.String())
}

// genderByte converts PokeAPI's gender_rate (female eighths, -1 genderless) to
// the game's threshold byte.
func genderByte(rate int) byte {
	switch {
	case rate < 0:
		return 255
	case rate == 0:
		return 0
	case rate >= 8:
		return 254
	default:
		return byte(rate * 255 / 8)
	}
}

// ---- Gen 1 types and catch rates -----------------------------------------

// gen1TypeID maps a modern type id (PokeAPI) to the Generation I internal
// numbering. Types that did not exist in Gen 1 return 0xFF.
var gen1TypeID = map[int]int{
	1: 0, 2: 1, 3: 2, 4: 3, 5: 4, 6: 5, 7: 6, 8: 7,
	11: 20, 10: 21, 12: 22, 13: 23, 14: 24, 15: 25, 16: 26,
}

func writeGen1Types(species, types, pokemon [][]string) {
	si := headerIndex(species[0])
	ti := headerIndex(types[0])
	pi := headerIndex(pokemon[0])

	catch := map[int]int{}
	for _, row := range species[1:] {
		catch[atoi(row[si["id"]])] = atoi(row[si["capture_rate"]])
	}
	// default form id -> species id
	speciesOf := map[int]int{}
	for _, row := range pokemon[1:] {
		if atoi(row[pi["is_default"]]) != 1 {
			continue
		}
		speciesOf[atoi(row[pi["id"]])] = atoi(row[pi["species_id"]])
	}
	pokemonTypes := map[int][]int{}
	for _, row := range types[1:] {
		pid := atoi(row[ti["pokemon_id"]])
		pokemonTypes[pid] = append(pokemonTypes[pid], atoi(row[ti["type_id"]]))
	}

	var typeTable [152][2]byte
	var catchTable [152]byte
	for national := 1; national <= 151; national++ {
		pokemonID := national
		modern := pokemonTypes[pokemonID]
		var gen1 []int
		seen := map[int]bool{}
		for _, t := range modern {
			id, ok := gen1TypeID[t]
			if !ok || seen[id] {
				continue
			}
			seen[id] = true
			gen1 = append(gen1, id)
		}
		if len(gen1) == 0 {
			gen1 = []int{0}
		}
		typeTable[national][0] = byte(gen1[0])
		typeTable[national][1] = byte(gen1[0])
		if len(gen1) > 1 {
			typeTable[national][1] = byte(gen1[1])
		}
		catchTable[national] = byte(catch[national])
	}
	_ = speciesOf

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("package pokemon\n\n")
	b.WriteString("// TypeGen1 holds the Generation I internal type ids (Normal..Dragon) of\n// each species, indexed by National Dex number.\n")
	b.WriteString("var TypeGen1 = [152][2]byte{")
	for i := 0; i < 152; i++ {
		if i%8 == 0 {
			b.WriteString("\n\t")
		}
		fmt.Fprintf(&b, "{%d,%d},", typeTable[i][0], typeTable[i][1])
	}
	b.WriteString("\n}\n\n")
	b.WriteString("// CatchRateGen1 holds the Generation I catch rate of each species.\n")
	b.WriteString("var CatchRateGen1 = [152]byte{")
	for i := 0; i < 152; i++ {
		if i%16 == 0 {
			b.WriteString("\n\t")
		}
		fmt.Fprintf(&b, "%d,", catchTable[i])
	}
	b.WriteString("\n}\n")
	writeFile("internal/pokemon/data_gen1types.go", b.String())
}

// ---- moves ---------------------------------------------------------------

// writeMoves emits the base PP of each move and the per-generation move-id
// limit. Move ids have been stable since Generation I, so a move's number is
// the same in every generation; only its existence (MaxMoveID) differs, which
// is why no per-generation translation table is needed.
func writeMoves(moves [][]string) {
	mi := headerIndex(moves[0])
	pp := map[int]int{}
	for _, row := range moves[1:] {
		pp[atoi(row[mi["id"]])] = atoi(row[mi["pp"]])
	}

	const size = 920
	var ppTable [size]byte
	for id := 1; id < size; id++ {
		if p, ok := pp[id]; ok && p < 255 {
			ppTable[id] = byte(p)
		}
	}

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("package xgen\n\n")
	b.WriteString("// MoveBasePP is the base PP of each move id.\n")
	fmt.Fprintf(&b, "var MoveBasePP = [%d]byte{", size)
	for i := 0; i < size; i++ {
		if i%16 == 0 {
			b.WriteString("\n\t")
		}
		fmt.Fprintf(&b, "%d,", ppTable[i])
	}
	b.WriteString("\n}\n\n")

	b.WriteString("// MaxMoveID is the highest move id each generation can store.\n")
	b.WriteString("var MaxMoveID = map[int]uint16{1: 165, 2: 251, 3: 354, 4: 467, 5: 559, 6: 728, 7: 919, 8: 919}\n")

	writeFile("internal/xgen/data_moves.go", b.String())
}

func writeFile(path, content string) {
	src, err := format.Source([]byte(content))
	if err != nil {
		must(fmt.Errorf("format %s: %w", path, err))
	}
	must(os.MkdirAll(filepath.Dir(path), 0o755))
	must(os.WriteFile(path, src, 0o644))
	fmt.Println("wrote", path)
}
