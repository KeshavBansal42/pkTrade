// MaxItemID per generation (the highest valid item ID).
var MaxItemID = map[int]uint16{
	1: 0,
	2: 254,
	3: 376,
	4: 467,
	5: 537,
	6: 720,
	7: 900,
	8: 1150,
}

// GetItemID returns the item ID for the given generation and name, or 0 if not found.
func GetItemID(gen int, name string) uint16 {
	switch gen {
	case 1:
		return 0 // Gen 1 has no held items
	case 2:
		return ItemIDGen2[name]
	case 3:
		return ItemIDGen3[name]
	case 4, 5, 6, 7, 8:
		if id, ok := ItemIDGen4Plus[name]; ok && id <= MaxItemID[gen] {
			return id
		}
	}
	return 0
}

// TranslateItem translates an item from source generation to destination generation.
// Returns (destID, existsInDest).
func TranslateItem(srcGen, dstGen int, srcItemID uint16) (uint16, bool) {
	if srcItemID == 0 {
		return 0, true
	}
	name := findItemName(srcGen, srcItemID)
	if name == "" {
		return 0, false
	}
	dstID := GetItemID(dstGen, name)
	return dstID, dstID != 0
}

func findItemName(gen int, id uint16) string {
	var m map[string]uint16
	switch gen {
	case 2:
		m = ItemIDGen2
	case 3:
		m = ItemIDGen3
	default:
		m = ItemIDGen4Plus
	}
	// Several display names can share one id ("X Attack" and "X Attack 2").
	// Pick the lexicographically smallest so the reverse lookup is stable.
	best := ""
	for name, itemID := range m {
		if itemID != id || name == "" {
			continue
		}
		if best == "" || name < best {
			best = name
		}
	}
	return best
}
